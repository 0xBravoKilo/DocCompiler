import os
import re
from pathlib import Path
from typing import List, Dict, Any

# Configuration
SOURCE_DIR = Path("./raw_docs")
OUTPUT_DIR = Path("./processed_docs")
MIN_CHUNK_SIZE = 500  # Minimum characters before forcing a new chunk
MAJOR_HEADER_LEVELS = [1, 2]  # Levels that always force a new chunk

class DocCompiler:
    def __init__(self, source: Path, output: Path, chunk_enabled: bool = False):
        self.source = source
        self.output = output
        self.chunk_enabled = chunk_enabled
        self.output.mkdir(parents=True, exist_ok=True)

    def run(self):
        """Main execution loop."""
        print(f"🚀 Starting compilation from {self.source}...")

        rst_files = list(self.source.rglob("*.rst"))
        print(f"📂 Found {len(rst_files)} .rst files.")

        for rst_file in rst_files:
            self.process_file(rst_file)

        print(f"✅ Compilation complete! Files are in {self.output}")

    def process_file(self, rst_path: Path):
        """Handles the conversion for a single file."""
        print(f"📄 Processing: {rst_path.relative_to(self.source)}")

        with open(rst_path, 'r', encoding='utf-8') as f:
            content = f.read()

        # 1. Parse and Transform to Markdown
        markdown_content = self.convert_rst_to_markdown(content)

        # 2. Semantic Chunking by Header
        if self.chunk_enabled:
            chunks = self.chunk_by_header(markdown_content)
        else:
            chunks = [{"content": markdown_content, "headers": []}]

        # 3. Write chunks to files
        relative_path = rst_path.relative_to(self.source)
        base_name = relative_path.stem

        for i, chunk in enumerate(chunks):
            suffix = f"_chunk_{i}" if self.chunk_enabled else ""
            chunk_path = self.output / relative_path.with_suffix(".md").parent / f"{base_name}{suffix}.md"
            chunk_path.parent.mkdir(parents=True, exist_ok=True)

            with open(chunk_path, 'w', encoding='utf-8') as f:
                # Join the headers into a string for metadata
                headers_str = ", ".join([f"{h[0]} {h[1]}" for h in chunk['headers']])
                metadata = f"---"
                metadata += f"\nSource: {rst_path.name}"
                metadata += f"\nChunk Index: {i}"
                metadata += f"\nHeaders: {headers_str}"
                metadata += f"\n---"
                f.write(metadata + "\n\n" + chunk['content'])

    def convert_rst_to_markdown(self, rst_content: str) -> str:
        """
        The core transformation engine.
        Converts Sphinx .rst to Clean Markdown.
        """
        # Pre-processing: Handle Literal Blocks (::)
        content = self.handle_literal_blocks(rst_content)

        # Remove common out-of-band metadata and internal labels
        lines = content.splitlines()
        filtered_lines = []
        for line in lines:
            # Strip metadata and internal labels
            if any(x in line for x in ["DO NOT EDIT THIS FILE", "Generated automatically", "XML source", ".. rst-class::", ".. _"]):
                continue
            if any(x in line for x in [".. toctree::", ".. centered::", ".. only::"]):
                continue
            filtered_lines.append(line)

        content = "\n".join(filtered_lines)

        # Handle Code Blocks (.. code::, .. code-block::)
        content = self.handle_code_blocks(content)

        # Handle Tables
        content = self.parse_tables(content)

        # Handle Headers
        lines = content.splitlines()
        processed_lines = []
        for line in lines:
            stripped = line.strip()
            if stripped.startswith('===') and len(stripped) > 1 and all(c == '=' for c in stripped):
                processed_lines.append(f"# {stripped.replace('=', '').strip()}")
            elif stripped.startswith('---') and len(stripped) > 1 and all(c == '-' for c in stripped):
                processed_lines.append(f"## {stripped.replace('-', '').strip()}")
            elif stripped.startswith('~~~') and len(stripped) > 1 and all(c == '~' for c in stripped):
                processed_lines.append(f"### {stripped.replace('~', '').strip()}")
            else:
                processed_lines.append(line)

        content = "\n".join(processed_lines)

        # Handle Notes/Warnings/Tips
        content = re.sub(r'\.\.\s+(note|warning|tip|important):', r'> **\1:**', content)

        # Handle Links
        content = re.sub(r':ref:`([^<]+)<([^>]+)>`', r'[\1](#\2)', content)
        content = re.sub(r'\[([^\]]+)\s+<([^>]+)>\]_', r'[\1](\2)', content)

        # Handle Class Inheritance
        content = re.sub(r'\*\*Inherits:\*\*\s*(.*)', r'**Inheritance:** \1', content)

        # Handle Roles (simple ones)
        content = re.sub(r':\w+:`([^`]+)`', r'\1', content)

        # Handle Field Lists (cleaning up common artifacts)
        content = re.sub(r':(\w+)\s+([^:]+):', r'**\1 \2**:', content)

        # Strip raw HTML/CSS blocks
        content = re.sub(r'.. raw:: html\n\s*(.*)', '', content, flags=re.DOTALL)
        content = re.sub(r'.. raw:: html\n\s*\n.*?\n\s*\n', '', content, flags=re.DOTALL)

        return content

    def handle_literal_blocks(self, content: str) -> str:
        """
        Handles the :: marker for literal blocks.
        If a line ends with ::, the following indented lines are treated as a code block.
        """
        lines = content.splitlines()
        new_lines = []
        i = 0
        while i < len(lines):
            line = lines[i]
            if line.strip().endswith("::") and not line.strip().startswith(".."):
                new_lines.append(line.rstrip("::").strip() + ":")
                i += 1

                code_block = []
                while i < len(lines):
                    current_line = lines[i]
                    if current_line.strip() == "" and i + 1 < len(lines) and lines[i+1].strip() != "":
                        break
                    if not current_line.startswith(" ") and not current_line.startswith("\t") and current_line.strip() != "":
                        break

                    code_block.append(current_line)
                    i += 1

                if code_block:
                    new_lines.append("```")
                    new_lines.extend(code_block)
                    new_lines.append("```")
                else:
                    new_lines.append(line)
            else:
                new_lines.append(line)
            i += 1
        return "\n".join(new_lines)

    def handle_code_blocks(self, content: str) -> str:
        """
        Converts .. code:: and .. code-block:: directives into Markdown code blocks.
        Handles optional language and captures indented content.
        """
        # Pattern matches:
        # 1. .. code:: [lang]
        # 2. .. code-block:: [lang]
        # 3. Optional :caption: or other options (skipped)
        # 4. Indented content
        pattern = r'\.\.\s+(?:code|code-block)::\s*(?:(\w+)\s*)?\n(?:(?:\s:.*?\n)+)?\n((?:\s{4}.*\n?)+)'

        def replace_code(match):
            lang = match.group(1) if match.group(1) else ""
            code_body = match.group(2).strip()
            # Remove the 4-space indentation from each line of the code body
            cleaned_body = "\n".join([line.strip() for line in code_body.splitlines()])
            return f"```{lang}\n{cleaned_body}\n```"

        return re.sub(pattern, replace_code, content, flags=re.MULTILINE)

    def parse_tables(self, content: str) -> str:
        new_content = []
        lines = content.splitlines()
        i = 0
        while i < len(lines):
            line = lines[i]
            if ".. table::" in line:
                chunk = []
                while i < len(lines):
                    chunk.append(lines[i])
                    if lines[i].strip().startswith("+---") and "+" in lines[i]:
                        if i + 1 == len(lines) or not (lines[i+1].strip().startswith('|') or lines[i+1].strip().startswith("+---")):
                            break
                    i += 1

                data_rows = []
                for c_line in chunk:
                    if c_line.strip().startswith('|') and c_line.strip().endswith('|'):
                        if not (c_line.strip().startswith('+-') and c_line.strip().endswith('-+')):
                            data_rows.append(c_line)

                if data_rows:
                    cleaned_rows = []
                    for row in data_rows:
                        cells = [c.strip() for c in row.strip('|').split('|')]
                        cleaned_cells = [re.sub(r'\\([ \(\)\:;,])', r'\1', c).replace('\\', '').strip() for c in cells]
                        cleaned_rows.append(f"| {' | '.join(cleaned_cells)} |")

                    if len(cleaned_rows) > 0:
                        num_cols = len(cleaned_rows[0].split('|')) - 1
                        if len(cleaned_rows) > 1:
                            separator = "|" + "|".join(["---"] * num_cols) + "|"
                            new_content.append("\n".join([cleaned_rows[0], separator] + cleaned_rows[1:]))
                        else:
                            new_content.append("\n".join(cleaned_rows))
                    else:
                        new_content.append("\n".join(chunk))
                else:
                    new_content.append("\n".join(chunk))
                continue
            else:
                new_content.append(line)
                i += 1
        return "\n".join(new_content)

    def chunk_by_header(self, content: str) -> List[Dict[str, Any]]:
        """
        Splits the markdown content into chunks based on header levels.
        Each chunk is a dictionary containing the 'content' and 'metadata'.

        This version includes:
        1. Contextual Headers: Prepends the full hierarchy to each chunk.
        2. Min Chunk Size: Prevents over-fragmentation of small sections.
        3. Major Header Split: Forces a new chunk on Level 1 or 2 headers.
        """
        chunks = []
        current_chunk = {"content": [], "header_stack": []}

        lines = content.splitlines()
        for line in lines:
            header_match = re.match(r'^(#{1,6})\s+(.*)', line)
            if header_match:
                # If we have content in the current chunk, save it before starting a new one
                if current_chunk["content"]:
                    current_text = "\n".join(current_chunk["content"])
                    current_level = len(current_chunk["header_stack"][-1][0]) if current_chunk["header_stack"] else 99
                    new_level = len(header_match.group(1))

                    should_split = (
                        len(current_text) >= MIN_CHUNK_SIZE or
                        new_level in MAJOR_HEADER_LEVELS or
                        new_level < current_level
                    )

                    if should_split:
                        context = ""
                        for hashes, title in current_chunk["header_stack"]:
                            context += f"{hashes} {title}\n"

                        chunks.append({
                            "content": context + "\n" + current_text,
                            "headers": list(current_chunk["header_stack"])
                        })

                # Update the header stack
                level = len(header_match.group(1))
                title = header_match.group(2).strip()

                if current_chunk["header_stack"]:
                    last_level = len(current_chunk["header_stack"][-1][0])
                    if level < last_level:
                        while current_chunk["header_stack"] and len(current_chunk["header_stack"][-1][0]) >= level:
                            current_chunk["header_stack"].pop()
                    elif level == last_level:
                        current_chunk["header_stack"][-1] = (header_match.group(1), title)
                    else:
                        current_chunk["header_stack"].append((header_match.group(1), title))
                else:
                    current_chunk["header_stack"].append((header_match.group(1), title))

                # Reset for new chunk
                current_chunk = {
                    "content": [f"{'#' * level} {title}"],
                    "header_stack": list(current_chunk["header_stack"])
                }
            else:
                current_chunk["content"].append(line)

        # Append the last chunk
        if current_chunk["content"]:
            context = ""
            for hashes, title in current_chunk["header_stack"]:
                context += f"{hashes} {title}\n"

            chunks.append({
                "content": context + "\n" + "\n".join(current_chunk["content"]),
                "headers": current_chunk["header_stack"]
            })

        return chunks

if __name__ == "__main__":
    compiler = DocCompiler(SOURCE_DIR, OUTPUT_DIR)
    compiler.run()
